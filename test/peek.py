import os
from playwright.sync_api import sync_playwright
SHOTS = os.environ.get('SHOTS', os.path.abspath('test/shots'))
os.makedirs(SHOTS, exist_ok=True)
katex = open('node_modules/katex/dist/katex.min.js').read()
body = open('dist/calc2-playground.html').read()
open('dist/test.html','w').write('<!doctype html><html><head><meta charset=utf8><meta name=viewport content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light}body{margin:0;font:14px system-ui}[hidden]{display:none!important}</style></head><body>' + body + '</body></html>')
errors = []; fails = []
def check(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg, flush=True)
    if not cond: fails.append(msg)
def setup(page):
    page.on('console', lambda m: errors.append(('console', m.text)) if m.type == 'error' else None)
    page.on('pageerror', lambda e: errors.append(('pageerror', str(e))))
    page.route('**/katex.min.js', lambda r: r.fulfill(status=200, content_type='application/javascript', body=katex))
    page.route('https://fonts.googleapis.com/**', lambda r: r.fulfill(status=200, content_type='text/css', body=''))
    page.route('https://fonts.gstatic.com/**', lambda r: r.abort())
URL = ('file://' + os.path.abspath('dist/test.html'))
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 1280, 'height': 900})
    page = ctx.new_page(); setup(page)
    page.goto(URL); page.wait_for_timeout(300)
    page.evaluate("() => { localStorage.clear(); sessionStorage.clear(); }"); page.reload(); page.wait_for_timeout(400)
    page.evaluate("() => { UI.Store.state.settings.sound = false; UI.Store.state.units.ibp.lessonDone = true; UI.go({name:'unit', unit:'ibp', tab:'practice'}); }"); page.wait_for_timeout(300)
    n = page.evaluate("() => UI.app.SET.ibp.items[0].p.steps.length")
    check(page.inner_text('[data-act="setHint"]').strip() == f'Show step 1 of {n}', f'hint button offers step 1 of {n}')
    check(page.query_selector('#peek .peek-step') is None, 'nothing shown until you ask')
    page.click('[data-act="setHint"]'); page.wait_for_timeout(300)
    t0 = page.evaluate("() => UI.app.SET.ibp.items[0].p.steps[0].title")
    check(page.query_selector('#peek0 .math-lines .katex') is not None and t0 in page.inner_text('#peek0'), 'step 1 appears with its worked math')
    check(page.inner_text('[data-act="setHint"]').strip() == f'Show step 2 of {n}', 'button moves on to step 2')
    page.click('[data-act="setHint"]'); page.wait_for_timeout(300)
    check(len(page.query_selector_all('#peek .peek-mini')) == 1 and page.query_selector('#peek1') is not None, 'step 1 folds to one line, step 2 is open')
    page.screenshot(path=f'{SHOTS}/50-peek-desktop.png', full_page=False)
    page.click('#peek .peek-mini[data-i="0"]'); page.wait_for_timeout(200)
    check(page.query_selector('#peek0') is not None and page.query_selector('#peek1') is None, 'tap a folded step to open it again (one open at a time)')
    for k in range(n):
        if page.is_enabled('[data-act="setHint"]'): page.click('[data-act="setHint"]'); page.wait_for_timeout(120)
    check(not page.is_enabled('[data-act="setHint"]') and f'All {n} steps shown' in page.inner_text('[data-act="setHint"]'), 'all steps shown, button done')
    check(page.evaluate("() => UI.problemContext().peeked") == n, 'Ask Claude knows how far you followed along')
    # persists
    page.fill('#mfS-in', page.evaluate("() => UI.app.SET.ibp.items[0].p.answer.ascii + ' + C'")); page.wait_for_timeout(800)
    page.reload(); page.wait_for_timeout(600)
    check(page.evaluate("() => UI.app.SET.ibp.items[0].hints") == n and page.query_selector('#peek .peek-step') is not None, 'revealed steps come back after a reload')
    # mastery: following every step still counts as practice, but earns the minimum
    before = page.evaluate("() => UI.Store.state.units.ibp.mastery")
    page.evaluate("() => { const S = UI.app.SET.ibp; S.items.forEach((it, k) => { if (k) { it.ans = ''; } }); S.stage = 'review'; UI.render(); }"); page.wait_for_timeout(200)
    page.click('[data-act="setGrade"]'); page.wait_for_timeout(500)
    res = page.evaluate("() => UI.app.SET.ibp.results[0].g.verdict")
    after = page.evaluate("() => UI.Store.state.units.ibp.mastery")
    check(res == 'correct' and after == max(0, before + 2 - 5 * 4), f'full peek earns minimum mastery ({before} -> {after})')
    check('You peeked at' in page.inner_text('#res0') if page.query_selector('#res0') else True, 'report notes the peeking')
    # instant check mode uses the same walkthrough
    page.click('[data-act="mode"][data-m="test"]'); page.wait_for_timeout(250)
    m = page.evaluate("() => UI.app.P.p.steps.length")
    check(page.inner_text('[data-act="hint"]').strip() == f'Show step 1 of {m}', 'instant check: same step-by-step hints')
    page.click('[data-act="hint"]'); page.wait_for_timeout(250)
    check(page.query_selector('#peek0 .math-lines') is not None, 'instant check: step 1 shows')
    # step-by-step mode keeps short text hints
    page.click('[data-act="mode"][data-m="steps"]'); page.wait_for_timeout(250)
    page.click('[data-act="hint"]'); page.wait_for_timeout(200)
    check(page.query_selector('#hints .hint') is not None, 'step-by-step mode keeps its short hints')
    ctx.close()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, color_scheme='dark', has_touch=True, is_mobile=True, device_scale_factor=2)
    page = ctx.new_page(); setup(page)
    page.goto(URL); page.wait_for_timeout(300)
    page.evaluate("() => { localStorage.clear(); sessionStorage.clear(); }"); page.reload(); page.wait_for_timeout(400)
    page.evaluate("() => { UI.Store.state.units.ibp.lessonDone = true; UI.go({name:'unit', unit:'ibp', tab:'practice'}); }"); page.wait_for_timeout(300)
    page.click('[data-act="setHint"]'); page.wait_for_timeout(200); page.click('[data-act="setHint"]'); page.wait_for_timeout(200); page.click('[data-act="setHint"]'); page.wait_for_timeout(400)
    check(page.evaluate("() => document.documentElement.scrollWidth") <= 390, 'phone: no sideways scroll with steps open')
    page.evaluate("() => window.scrollTo(0, 0)"); page.wait_for_timeout(200)
    page.screenshot(path=f'{SHOTS}/51-peek-phone.png', full_page=True)
    ctx.close(); b.close()
print('ERRORS', len(errors)); [print(e) for e in errors[:20]]
print('FAILS', len(fails)); [print(' -', f) for f in fails]
