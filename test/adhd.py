import os
from playwright.sync_api import sync_playwright
SHOTS = os.environ.get('SHOTS', os.path.abspath('test/shots'))
os.makedirs(SHOTS, exist_ok=True)
katex = open('node_modules/katex/dist/katex.min.js').read()
errors = []; fails = []
def check(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg, flush=True)
    if not cond: fails.append(msg)
def setup(page):
    page.on('console', lambda m: errors.append(('console', m.text)) if m.type == 'error' else None)
    page.on('pageerror', lambda e: errors.append(('pageerror', str(e))))
    page.route('**/katex.min.js', lambda r: r.fulfill(status=200, content_type='application/javascript', body=katex))
    page.route('https://fonts.googleapis.com/**', lambda r: r.fulfill(status=200, content_type='text/css', body=''))
    page.route('https://fonts.gstatic.com/**', lambda r: r.abort())
URL = ('file://' + os.path.abspath('dist/test.html'))
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 1280, 'height': 900})
    page = ctx.new_page(); setup(page)
    page.goto(URL); page.wait_for_timeout(300)
    page.evaluate("() => { localStorage.clear(); sessionStorage.clear(); }"); page.reload(); page.wait_for_timeout(500)
    page.evaluate("() => { UI.Store.state.settings.sound = false; }")
    cta = page.inner_text('[data-act="nextUp"]')
    check('Start the lesson' in cta and page.get_attribute('[data-act="nextUp"]', 'data-tab') == 'learn', f'brand new: next step is the lesson ({cta.strip()})')
    check(page.query_selector('#heroArt') is None, 'no constantly-moving hero animation')
    page.screenshot(path=f'{SHOTS}/40-home-new.png', full_page=False)
    page.evaluate("() => { UI.Store.state.units.ibp.lessonDone = true; UI.render(); }"); page.wait_for_timeout(200)
    cta = page.inner_text('[data-act="nextUp"]')
    check('Start a quiz set' in cta and 'about 10 minutes' in page.inner_text('.nu-note'), f'then: start a quiz set with a time estimate ({cta.strip()})')
    check('strong set' in page.inner_text('.milestone'), 'concrete milestone instead of just a percent')
    check(page.query_selector('[data-act="justOne"]') is not None, 'low-effort "Just 1 problem" start')
    page.click('[data-act="justOne"]'); page.wait_for_timeout(300)
    check(len(page.query_selector_all('.numnav button')) == 1 and page.query_selector('.focusbar') is not None, 'Just 1 = a one-problem set in focus mode')
    page.evaluate("() => { delete UI.app.SET.ibp; UI.go({name:'unit', unit:'ibp', tab:'practice'}); }"); page.wait_for_timeout(300)
    nxt = page.inner_text('#setNext')
    check('Skip for now' in nxt, f'empty answer: button says skip ({nxt.strip()})')
    check('5 to go' in page.inner_text('#setCount'), 'friendly progress text')
    page.fill('#mfS-in', 'x'); page.wait_for_timeout(100)
    check('Next problem' in page.inner_text('#setNext'), 'typed answer: button says next')
    page.press('#mfS-in', 'Enter'); page.wait_for_timeout(250)
    check('1 down, 4 to go' in page.inner_text('#setCount'), 'progress text updates')
    check('pop' in (page.get_attribute('.numnav [data-k="0"]', 'class') or ''), 'answered dot pops')
    # answer the rest except the last, then the review shortcut appears
    for k in range(1, 4):
        page.fill('#mfS-in', 'x'); page.press('#mfS-in', 'Enter'); page.wait_for_timeout(150)
    page.click('[data-act="setJump"][data-k="0"]'); page.wait_for_timeout(150)
    check(page.query_selector('#setCta [data-act="setReview"]') is None, 'no review shortcut until all answered')
    page.click('[data-act="setJump"][data-k="4"]'); page.wait_for_timeout(150)
    page.fill('#mfS-in', 'x'); page.wait_for_timeout(100)
    page.click('[data-act="setJump"][data-k="2"]'); page.wait_for_timeout(150)
    check(page.query_selector('#setCta [data-act="setReview"]') is not None, 'all answered: review shortcut shows')
    page.screenshot(path=f'{SHOTS}/41-focus-desktop.png', full_page=False)
    # sprint + ribbon
    page.click('[data-act="sprint"]'); page.wait_for_timeout(700)
    rib = page.evaluate("() => { const r = document.getElementById('ribbon'); return { hidden: r.hidden, w: r.firstElementChild.style.width }; }")
    check(not rib['hidden'] and rib['w'] not in ('', '0%'), f'sprint shows a time bar {rib}')
    check('min' in page.inner_text('#fbSprint'), 'focus bar shows minutes left')
    page.evaluate("() => { const t = UI.Sprint.state; t.end = Date.now() + 1000; }"); page.wait_for_timeout(1800)
    check(page.evaluate("() => UI.Sprint.state.mode") == 'break' and page.evaluate("() => UI.Sprint.state.running"), 'sprint end starts a break on its own')
    page.evaluate("() => { const t = UI.Sprint.state; t.end = Date.now() + 500; }"); page.wait_for_timeout(1400)
    check(page.evaluate("() => UI.Sprint.state.mode") == 'focus' and page.evaluate("() => document.getElementById('ribbon').hidden"), 'break end: back to ready, bar hidden')
    # focus sound
    page.click('[data-act="noise"]'); page.wait_for_timeout(300)
    on = page.evaluate("() => UI.Noise.on")
    check(on and page.get_attribute('.focusbar [data-act="noise"]', 'aria-pressed') == 'true', 'brown noise toggles on')
    page.click('[data-act="noise"]'); page.wait_for_timeout(200)
    check(not page.evaluate("() => UI.Noise.on"), 'and off')
    # grade -> break tip + daily goal
    page.evaluate("() => { UI.Store.state.settings.goal = 5; }")
    page.click('[data-act="setJump"][data-k="4"]'); page.wait_for_timeout(150)
    page.click('[data-act="setReview"] >> nth=-1'); page.wait_for_timeout(200)
    page.click('[data-act="setGrade"]'); page.wait_for_timeout(2200)
    check(page.query_selector('.break-tip [data-act="takeBreak"]') is not None, 'report offers a short break')
    check(page.evaluate("() => UI.Store.state.goalDay") != '', 'daily goal reached gets celebrated')
    toasts = page.inner_text('.toast-wrap') if page.query_selector('.toast-wrap') else ''
    check('Daily goal' in toasts, 'daily goal toast')
    page.click('[data-act="takeBreak"]'); page.wait_for_timeout(300)
    check(page.evaluate("() => UI.Sprint.state.mode === 'break' && UI.Sprint.state.running && UI.Sprint.state.total === 120"), '2-minute break timer runs')
    page.evaluate("() => UI.Sprint.reset()")
    page.screenshot(path=f'{SHOTS}/42-report-one.png', full_page=False)
    # home after: resume / ring
    page.evaluate("() => UI.go({name:'home'})"); page.wait_for_timeout(200)
    ring = page.inner_text('.gr-n')
    check(ring.strip().startswith('5'), f'today ring counts problems ({ring.strip()})')
    page.evaluate("() => { UI.Store.state.settings.goal = 10; UI.go({name:'unit', unit:'ibp', tab:'practice'}); }"); page.wait_for_timeout(200)
    page.click('[data-act="setNew"]'); page.wait_for_timeout(200)
    page.fill('#mfS-in', 'x'); page.wait_for_timeout(800)
    page.evaluate("() => UI.go({name:'home'})"); page.wait_for_timeout(200)
    check('Resume your set' in page.inner_text('[data-act="nextUp"]') and '1 of 5 answered' in page.inner_text('.nu-note'), 'home offers to resume where you left off')
    # timer tool ring
    page.click('.dock-btn[data-tool="timer"]'); page.wait_for_timeout(400)
    check(page.query_selector('#tmArc') is not None, 'timer tool shows a ring that empties')
    page.click('[data-close-tool]'); page.wait_for_timeout(200)
    # boss quiz in focus mode
    page.evaluate("() => { UI.Store.state.units.ibp.mastery = 100; UI.app.Q = null; UI.go({name:'unit', unit:'ibp', tab:'quiz'}); }"); page.wait_for_timeout(200)
    page.click('[data-act="startQuiz"]'); page.wait_for_timeout(300)
    check(page.query_selector('.focusbar') is not None and 'Boss Quiz' in page.inner_text('.fb-title'), 'boss quiz runs in focus mode')
    # settings toggle off focus
    page.click('[data-act="settings"]'); page.wait_for_timeout(200)
    page.click('#setFocus'); page.wait_for_timeout(200)
    page.click('.modal [data-act="closeModal"]'); page.wait_for_timeout(200)
    check(page.query_selector('.focusbar') is None and page.query_selector('.unit-head') is not None, 'focus mode can be turned off in settings')
    ctx.close()
    # phone screenshots
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, color_scheme='dark', has_touch=True, is_mobile=True, device_scale_factor=2)
    page = ctx.new_page(); setup(page)
    page.goto(URL); page.wait_for_timeout(300)
    page.evaluate("() => { localStorage.clear(); sessionStorage.clear(); }"); page.reload(); page.wait_for_timeout(400)
    page.evaluate("() => { UI.Store.state.units.ibp.lessonDone = true; UI.render(); }"); page.wait_for_timeout(200)
    page.screenshot(path=f'{SHOTS}/43-phone-home.png', full_page=False)
    page.click('[data-act="nextUp"]'); page.wait_for_timeout(300)
    page.screenshot(path=f'{SHOTS}/44-phone-focus.png', full_page=False)
    check(page.evaluate("() => document.documentElement.scrollWidth") <= 390, 'phone: no sideways scroll')
    ctx.close(); b.close()
print('ERRORS', len(errors)); [print(e) for e in errors[:20]]
print('FAILS', len(fails)); [print(' -', f) for f in fails]
